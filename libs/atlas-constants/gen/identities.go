// Package main implements the atlas-constants identity generator (task-187).
//
// It owns the version-blind "identity" namespace layered on top of the
// existing wire-id constants in skill/constants.go and job/constants.go:
// each identity has a stable Go name and an opaque canonical token (the
// current v83 wire id for that name). Later tasks (3-6) extend this with
// per-version wireId -> identity bindings; this generator only assembles
// and emits the namespace itself.
package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// IdentityEntry is one row of identities.yaml: a domain-scoped identity name
// bound to its canonical (v83-era) wire-id token.
type IdentityEntry struct {
	Name           string `yaml:"name"`
	Domain         string `yaml:"domain"`
	CanonicalToken uint64 `yaml:"canonicalToken"`
	DisplayName    string `yaml:"displayName"`
}

// LoadIdentities reads and parses the checked-in identities.yaml source of
// truth into a slice of IdentityEntry.
func LoadIdentities(path string) ([]IdentityEntry, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", path, err)
	}
	var ids []IdentityEntry
	if err := yaml.Unmarshal(b, &ids); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}
	return ids, nil
}

// ValidateIdentityTokens errors on a duplicate canonicalToken within the
// same domain -- two identities in the same domain must not share a wire
// id, or the generated Go const block would not compile (two consts with
// the same value is legal, but two different identities silently aliasing
// the same wire id would be a modelling bug, not an accepted pattern).
func ValidateIdentityTokens(ids []IdentityEntry) error {
	seen := make(map[string]map[uint64]string)
	for _, id := range ids {
		if seen[id.Domain] == nil {
			seen[id.Domain] = make(map[uint64]string)
		}
		if existing, ok := seen[id.Domain][id.CanonicalToken]; ok {
			return fmt.Errorf("duplicate canonicalToken %d in domain %q: %s and %s", id.CanonicalToken, id.Domain, existing, id.Name)
		}
		seen[id.Domain][id.CanonicalToken] = id.Name
	}
	return nil
}

// domains is the fixed set of identity domains this generator emits, in
// emission order. Each domain name doubles as its target package name
// (skill.Identity lives in package skill, job.Identity in package job).
// Adding a new domain requires a new entry here plus a corresponding
// hand-written identity.go in the target package.
var domains = []string{"skill", "job"}

// EmitIdentities renders the generated Go source for the skill and job
// identity const blocks, in that order.
func EmitIdentities(ids []IdentityEntry) (skillGo string, jobGo string) {
	rendered := make(map[string]string, len(domains))
	for _, d := range domains {
		rendered[d] = emitDomain(ids, d)
	}
	return rendered["skill"], rendered["job"]
}

func emitDomain(ids []IdentityEntry, domain string) string {
	var filtered []IdentityEntry
	for _, id := range ids {
		if id.Domain == domain {
			filtered = append(filtered, id)
		}
	}
	sort.Slice(filtered, func(i, j int) bool {
		if filtered[i].CanonicalToken != filtered[j].CanonicalToken {
			return filtered[i].CanonicalToken < filtered[j].CanonicalToken
		}
		return filtered[i].Name < filtered[j].Name
	})

	var b strings.Builder
	b.WriteString("// Code generated by gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", domain)
	b.WriteString("const (\n")
	for _, id := range filtered {
		fmt.Fprintf(&b, "\t%s Identity = %d\n", id.Name, id.CanonicalToken)
	}
	b.WriteString(")\n\n")
	b.WriteString("var identityNames = map[Identity]string{\n")
	for _, id := range filtered {
		fmt.Fprintf(&b, "\t%s: %q,\n", id.Name, id.DisplayName)
	}
	b.WriteString("}\n")
	return b.String()
}

// idConstRe matches one `<Name>Id = Id(<token>)` line from skill/constants.go
// or job/constants.go's const blocks, e.g. `SuperGmHideId = Id(9101004)`.
// It intentionally does not match the job package's separate
// `Type = Type(N)` block -- that uses a different right-hand-side type name.
var idConstRe = regexp.MustCompile(`^\s*([A-Za-z][A-Za-z0-9]*)Id\s*=\s*Id\((\d+)\)\s*$`)

// humanizeBoundaryRe inserts a space at PascalCase word boundaries: between
// a lowercase/digit and a following uppercase letter, and between the last
// letter of an acronym run and the capitalized word that follows it (e.g.
// "HPBoost" -> "HP Boost", "SuperGmHide" -> "Super Gm Hide").
var humanizeBoundaryRe = regexp.MustCompile(`([a-z0-9])([A-Z])|([A-Z]+)([A-Z][a-z])`)

func humanize(name string) string {
	return humanizeBoundaryRe.ReplaceAllString(name, "$1$3 $2$4")
}

// bootstrapFromConstants performs the one-off mechanical extraction (task-2
// brief Step 1): parse the `<Name>Id = Id(<token>)` const lines out of
// skill/constants.go and job/constants.go and emit one IdentityEntry per
// constant, named by stripping the trailing "Id" and keyed by domain.
func bootstrapFromConstants(skillConstantsPath, jobConstantsPath string) ([]IdentityEntry, error) {
	var out []IdentityEntry
	for _, src := range []struct {
		path   string
		domain string
	}{
		{path: skillConstantsPath, domain: "skill"},
		{path: jobConstantsPath, domain: "job"},
	} {
		entries, err := extractIdConsts(src.path, src.domain)
		if err != nil {
			return nil, err
		}
		out = append(out, entries...)
	}
	return out, nil
}

func extractIdConsts(path, domain string) ([]IdentityEntry, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, fmt.Errorf("opening %s: %w", path, err)
	}
	defer func() { _ = f.Close() }()

	var out []IdentityEntry
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := idConstRe.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		name := m[1]
		var token uint64
		if _, err := fmt.Sscanf(m[2], "%d", &token); err != nil {
			return nil, fmt.Errorf("%s: parsing token in %q: %w", path, sc.Text(), err)
		}
		out = append(out, IdentityEntry{
			Name:           name,
			Domain:         domain,
			CanonicalToken: token,
			DisplayName:    humanize(name),
		})
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("scanning %s: %w", path, err)
	}
	return out, nil
}

// marshalIdentities renders identities.yaml deterministically: grouped by
// domain (skill then job), ascending by canonicalToken within each domain --
// the same ordering EmitIdentities uses, so the checked-in YAML reads in the
// same order as the generated Go const blocks.
func marshalIdentities(ids []IdentityEntry) ([]byte, error) {
	sorted := make([]IdentityEntry, len(ids))
	copy(sorted, ids)
	domainOrder := map[string]int{"skill": 0, "job": 1}
	sort.SliceStable(sorted, func(i, j int) bool {
		di, dj := domainOrder[sorted[i].Domain], domainOrder[sorted[j].Domain]
		if di != dj {
			return di < dj
		}
		return sorted[i].CanonicalToken < sorted[j].CanonicalToken
	})
	return yaml.Marshal(sorted)
}
