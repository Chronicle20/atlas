// registry.go implements the atlas-constants tenant-keyed selector
// generator (task-187 Task 6): the single entry point layered on top of
// Tasks 2-5's per-version skill/job Sets.
//
// Pipeline:
//
//	provisionedVersions (this package's literal, task-187 Task 4)
//	  --[EmitRegistry]--> constants/registry_gen.go
//	    (map[versionKey]SkillJobSet keyed by every provisioned tenant
//	    version, built from skill/job's generated NewSet<PascalVersion>
//	    exported constructors)
//	  --[EmitBaseline]--> skill/baseline_gen.go, job/baseline_gen.go
//	    (the canonical GMS 83.1 fallback Set, exposed as skill.Baseline() /
//	    job.Baseline() -- constants.For falls back to this when the
//	    requested tuple is not a registry key)
//
// GMS 83.1 is the canonical baseline: see
// docs/tasks/task-187-version-aware-id-semantics (v83 is the audit's
// reference version; every other provisioned version's divergences are
// recorded relative to it).
package main

import (
	"fmt"
	"strings"
)

const (
	registryGenPath      = "../constants/registry_gen.go"
	skillBaselineGenPath = "../skill/baseline_gen.go"
	jobBaselineGenPath   = "../job/baseline_gen.go"
)

// EmitRegistry renders constants/registry_gen.go: the versionKey type, the
// map[versionKey]SkillJobSet literal for every provisioned tenant version
// (each entry built from that version's generated
// skill.NewSet<PascalVersion>() / job.NewSet<PascalVersion>() exported
// constructors), and the baseline var used by constants.For's fallback
// path.
func EmitRegistry() string {
	var b strings.Builder
	b.WriteString("// Code generated by gen; DO NOT EDIT.\n\n")
	b.WriteString("package constants\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"github.com/Chronicle20/atlas/libs/atlas-constants/job\"\n")
	b.WriteString("\t\"github.com/Chronicle20/atlas/libs/atlas-constants/skill\"\n")
	b.WriteString(")\n\n")

	b.WriteString("// versionKey identifies one provisioned (region, major, minor) tenant\n")
	b.WriteString("// version column in registry below (task-187 Task 6). region is always\n")
	b.WriteString("// upper-cased -- For upper-cases its input region before lookup, so the\n")
	b.WriteString("// registry's keys are upper-cased too.\n")
	b.WriteString("type versionKey struct {\n")
	b.WriteString("\tregion       string\n")
	b.WriteString("\tmajor, minor uint16\n")
	b.WriteString("}\n\n")

	b.WriteString("// registry is every provisioned tenant version's SkillJobSet, built from\n")
	b.WriteString("// the skill/job packages' per-version generated NewSet<PascalVersion>\n")
	b.WriteString("// constructors (task-187 Tasks 2-5). constants.For looks a requested\n")
	b.WriteString("// (region,major,minor) tuple up here, falling back to baseline on a miss.\n")
	b.WriteString("var registry = map[versionKey]SkillJobSet{\n")
	for _, v := range provisionedVersions {
		region := strings.ToUpper(v.Region)
		name := pascalVersionName(v)
		fmt.Fprintf(&b, "\t{%q, %d, %d}: {Skill: skill.NewSet%s(), Job: job.NewSet%s()},\n", region, v.Major, v.Minor, name, name)
	}
	b.WriteString("}\n\n")

	b.WriteString("// baseline is the canonical fallback SkillJobSet (GMS 83.1) constants.For\n")
	b.WriteString("// returns for an unprovisioned (region,major,minor) tuple.\n")
	b.WriteString("var baseline = SkillJobSet{Skill: skill.Baseline(), Job: job.Baseline()}\n")

	return b.String()
}

// EmitBaseline renders skill/baseline_gen.go and job/baseline_gen.go: each
// package's exported Baseline() constructor wrapping the canonical GMS 83.1
// newSet_gms_83_1 (task-187 Task 6). Kept in their own file (rather than
// folded into version_gms_83_1_gen.go) so "this is THE fallback version" is
// discoverable independent of the general per-version file naming.
func EmitBaseline() (skillGo, jobGo string) {
	skillGo = baselineGenPackage("skill")
	jobGo = baselineGenPackage("job")
	return skillGo, jobGo
}

func baselineGenPackage(domain string) string {
	var b strings.Builder
	b.WriteString("// Code generated by gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", domain)
	b.WriteString("// Baseline returns the canonical fallback identity Set (GMS 83.1),\n")
	b.WriteString("// generated by newSet_gms_83_1 (task-187 Tasks 2-5). constants.For\n")
	b.WriteString("// (task-187 Task 6) returns this when the requested (region,major,minor)\n")
	b.WriteString("// tuple is not a provisioned registry key.\n")
	b.WriteString("func Baseline() Set {\n")
	b.WriteString("\treturn newSet_gms_83_1()\n")
	b.WriteString("}\n")
	return b.String()
}
