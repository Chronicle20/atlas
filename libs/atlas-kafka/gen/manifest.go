package main

import (
	"bytes"
	"fmt"
	"os"

	"gopkg.in/yaml.v3"
)

// Entry is one topic.Token constant collected from the workspace: its
// string value, the cleanup policy its topic must carry (Tasks 6-8 render
// this into the ConfigMap/overlay), and the sorted set of packages (by
// PkgPath) that declare it.
type Entry struct {
	Token    string
	Cleanup  string
	Packages []string
}

// Manifest is the full, sorted set of topic.Token constants collected by
// Scan. Tasks 6, 7, and 8 consume this (and the topics.yaml it emits) to
// render ConfigMaps, overlays, and the drift gate.
type Manifest struct {
	Topics []Entry
}

// topicsYAMLHeader is emitted verbatim above the topics list.
const topicsYAMLHeader = `# GENERATED by libs/atlas-kafka/gen -- do not edit.
# Source of truth: topic.Token constants in services/ and libs/.
# Regenerate: tools/gen-topics.sh    Drift check: tools/gen-topics.sh --check
`

// yamlEntry/yamlManifest mirror Entry/Manifest with the yaml.v3 field tags
// that control topics.yaml's on-disk key names and ordering.
type yamlEntry struct {
	Token    string   `yaml:"token"`
	Cleanup  string   `yaml:"cleanup"`
	Packages []string `yaml:"packages"`
}

type yamlManifest struct {
	Topics []yamlEntry `yaml:"topics"`
}

// EmitTopicsYAML renders m as topics.yaml's bytes, header included.
func (m Manifest) EmitTopicsYAML() []byte {
	ym := yamlManifest{Topics: make([]yamlEntry, 0, len(m.Topics))}
	for _, e := range m.Topics {
		ym.Topics = append(ym.Topics, yamlEntry{Token: e.Token, Cleanup: e.Cleanup, Packages: e.Packages})
	}

	var buf bytes.Buffer
	buf.WriteString(topicsYAMLHeader)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(ym); err != nil {
		// yamlManifest is a plain struct of strings/slices; encoding it
		// cannot fail.
		panic(fmt.Sprintf("encoding topics.yaml: %v", err))
	}
	_ = enc.Close()
	return buf.Bytes()
}

// checkDrift compares the file at path against want byte-for-byte,
// mirroring libs/atlas-constants/gen/main.go's checkDrift.
func checkDrift(path string, want []byte) error {
	got, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("%s: %w (run `go run .` to generate it)", path, err)
	}
	if !bytes.Equal(got, want) {
		return fmt.Errorf("%s is stale relative to the workspace scan -- run `go run .` to regenerate", path)
	}
	return nil
}
