package main

import (
	"bytes"
	"fmt"
)

// EmitEnvConfigMapBlock renders the topic entries of m as the
// `  TOKEN: "TOKEN"` lines Splice inserts into deploy/k8s/base's
// env-configmap.yaml `# BEGIN generated:topics` / `# END generated:topics`
// region. The mapping is the identity (token -> token); overlays are
// responsible for the per-environment suffix (FR-3.1).
func (m Manifest) EmitEnvConfigMapBlock() []byte {
	var buf bytes.Buffer
	for _, e := range m.Topics {
		fmt.Fprintf(&buf, "  %s: %q\n", e.Token, e.Token)
	}
	return buf.Bytes()
}

// topicsConfigMapHeader is emitted verbatim above the ConfigMap manifest.
const topicsConfigMapHeader = `# GENERATED by libs/atlas-kafka/gen -- do not edit. Run tools/gen-topics.sh.
#
# The topic set atlas-kafka-precreate creates, mounted into that Job at
# /etc/atlas/topics/topics.yaml. Carries only the token and its cleanup
# policy; the resolved per-environment topic name comes from atlas-env,
# which the overlays generate from the same manifest.
apiVersion: v1
kind: ConfigMap
metadata:
  name: atlas-kafka-topics
  annotations:
    # Wave -1: this ConfigMap is mounted by the wave-0 atlas-kafka-precreate
    # Job. ArgoCD applies same-wave resources before health-checking any of
    # them and a configMap volume resolves at pod start, so a same-wave
    # ConfigMap races the Job into ContainerCreating.
    argocd.argoproj.io/sync-wave: "-1"
data:
  topics.yaml: |
`

// EmitTopicsConfigMap renders m as the whole, wholly-generated
// deploy/k8s/base/kafka-topics-configmap.yaml. Unlike topics.yaml, the
// mounted copy carries only token/cleanup pairs -- provenance (Packages)
// is stripped (design §5).
func (m Manifest) EmitTopicsConfigMap() []byte {
	var buf bytes.Buffer
	buf.WriteString(topicsConfigMapHeader)
	buf.WriteString("    topics:\n")
	for _, e := range m.Topics {
		fmt.Fprintf(&buf, "      - token: %s\n        cleanup: %s\n", e.Token, e.Cleanup)
	}
	return buf.Bytes()
}
